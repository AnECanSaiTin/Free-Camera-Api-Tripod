package cn.anecansaitin.free_camera_api_tripod_v2.api.animation.block;

import org.jspecify.annotations.NullMarked;

/// 标记的种类（主设计 §3.1、§9.1；UI 设计 §6.4）。
///
/// 标记是**文档一等概念**，不是塞进扩展轨道的附属数据。它同时服务四件事：
///
/// | 用途 | 说明 |
/// | --- | --- |
/// | 音频卡点 | A1 阶段由波形创建的节拍候选，**经作者显式确认**后才提交为标记 |
/// | 吸附源 | 时间轴吸附的候选来源之一，可由作者逐源开关 |
/// | 注释 | 作者写给自己的说明，不产生任何运行期行为 |
/// | 事件参考 | 作为对齐参照，**本身不触发 Tick 事件** |
///
/// 最后一条很重要：标记**不是事件**。事件由文档级 Tick 轨道驱动，
/// 标记只影响编辑显示与吸附，不进入正式播放的执行路径。
@NullMarked
public enum MarkerKind {
    /// 普通注释标记。
    GENERIC,

    /// 节拍点：由波形分析产生候选、作者确认后提交。
    BEAT,

    /// 章节或段落边界，用于长动画分段导航。
    SECTION
}
