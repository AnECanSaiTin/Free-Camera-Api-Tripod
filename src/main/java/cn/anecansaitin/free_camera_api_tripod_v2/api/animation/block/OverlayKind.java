package cn.anecansaitin.free_camera_api_tripod_v2.api.animation.block;

import org.jspecify.annotations.NullMarked;

/// 成片叠加元素的种类（主设计 §7.8，D26）。
///
/// 四类都在范围内，但**独立分期**交付，不捆绑成一次：
///
/// | 阶段 | 内容 |
/// | --- | --- |
/// | O1 | 遮幅（letterbox） |
/// | O2 | 字幕与图片（资源、字体、对齐、时间区间） |
/// | O3 | 不透明度与淡入淡出 |
///
/// ## 与编辑构图辅助的区别
///
/// 构图安全框、三分线、画幅参照与可视化遮幅预览是**编辑器辅助**，
/// 属于会话视图状态，**不随成片输出**（主设计 §7.8；UI 设计 §7.3）。
/// 需要真正进入播放画面的遮幅，必须建立本包的文档叠加元素。
///
/// 两者极易混淆，因此界面必须让作者看得见差异：编辑辅助永远不进成片。
///
/// ## 淡入淡出不是镜头过渡
///
/// 淡入淡出**只改变某个元素自身的不透明度**，不是机位之间的镜头过渡。
/// 本轮明确不做镜头过渡与混合（主设计 §1），不能借这个字段把过渡做进来。
@NullMarked
public enum OverlayKind {
    /// 遮幅：在画面上加黑边，改变有效画幅。
    LETTERBOX,

    /// 字幕：文本内容 + 字体、对齐与时间区间。
    SUBTITLE,

    /// 图片：资源引用 + 布局与时间区间。
    IMAGE
}
