package cn.anecansaitin.free_camera_api_tripod_v2.api.spatial;

import net.minecraft.resources.Identifier;
import org.jspecify.annotations.NullMarked;

/// 锚点：机位局部空间的参考原点，或注视目标的位置来源（主设计 §6.3）。
///
/// ## 开放契约
///
/// 锚点是**开放不可变契约**：内置类型有固定坐标、实体 UUID、玩家 UUID，
/// 第三方可注册自己的类型（主设计 D16：数据类型扩展开放轨道、锚点与世界采样三类）。
///
/// 实现必须深不可变（主设计 §3.2）：
///
/// - 字段只用不可变值，不持有可变集合；
/// - 不持有 `Level`、`Entity` 一类活对象——世界事实每帧由 `AnchorResolver` 解析，
///   文档里只存**静态坐标或身份引用**（UUID、类型 ID 与参数）。
///
/// “第三方对象的不可变性是扩展契约，不能宣称由开放 Java 接口完全强制”（主设计 §3.2），
/// 因此框架只保证自己持有的外层容器被复制。
///
/// ## 与“播放请求覆盖锚点”的关系
///
/// 锚点有三种来源，优先级从高到低：播放请求按 `RigId` 的覆盖 → 机位文档默认值 →
/// 无（局部空间允许没有默认锚点，但开始播放前必须由请求提供）。
/// 一旦选定的覆盖锚点解析失败，**不得回退到文档默认锚点**（主设计 §6.3）——
/// 那会让“失败”伪装成“另一个坐标”，违反不变量 I9。
///
/// ## 网络
///
/// 网络传输锚点**类型与完整参数**，不传选择器字符串（主设计 D12）：
/// 选择器由服务端执行并解析成具体锚点，客户端收到的是可解析的具体对象。
@NullMarked
public interface Anchor {

    /// 锚点类型标识，用于注册表分派解码器与解析器。
    ///
    /// 类型不存在在**解码期**报错（主设计 §7.7 对采样类型的同一条规则）；
    /// 类型已注册但客户端解析器缺失，则是**运行能力缺失**，属于另一类诊断，
    /// 不能与前者合并成同一条错误。
    Identifier type();
}
